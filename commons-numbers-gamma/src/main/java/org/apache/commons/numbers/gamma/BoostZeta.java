    /**
     * Returns the Riemann zeta function.
     *
     * @param s Argument.
     * @return zeta(s)
     */
    static double zeta(double s) {
        if (Double.isNaN(s) || s == Double.NEGATIVE_INFINITY) {
            return Double.NaN;
        }
        return zetaImp(s, 1 - s);
    }

    /**
     * Implementation for the zeta function.
     * Adapted from {@code boost::math::special_functions::zeta::zeta_imp}.
     *
     * @param s Argument.
     * @param sc Complement argument (1 - s).
     * @return zeta(s)
     */
    private static double zetaImp(double s, double sc) {
        if (sc == 0) {
            return Double.POSITIVE_INFINITY;
        }
        //
        // Trivial case:
        //
        if (s > 53.0000000001) {
            return 1;
        }
        //
        // Start by seeing if we have a simple closed form for integer s:
        //
        if (Math.floor(s) == s) {
            // Change from Boost implementation.
            // Handle any negative even integer. Values below -(2^63) are clipped
            // to -(2^63) and will be even.
            if (s < 0 && ((long) s & 1) == 0) {
                // Negative even integer
                return 0;
            }

            // Special handling for small integer s
            int v = (int) s;
            if (v == s) {
                if (v < 0) {
                    // Negative odd integer
                    int n = (1 - v) / 2;
                    if (n < B2N.length) {
                        return -B2N[n] / (1 - v);
                    }
                // Note:
                // Change from the Boost implementation to remove positive even integer case:
                //   2^(v-1) * pow(pi, v) * abs(B2N[v/2]) / v!
                // Code to handle positive even integers is less accurate than the rational
                // function approximation. zetaImp53 is exact except for 1 ULP at s=2.
//                } else if ((v & 1) == 0) {
//                    // Positive even integer.
//                    // This is inaccurate as s increases in size due to pow(pi, v).
//                    // When s >= 34 then zeta = 1 + 2^-s (as 3^-s is below machine epsilon).
//                    if (s < 3) {
//                        int n = v / 2;
//                        // This is always within the max B2N and factorial
//                        return
//                            // (((n - 1) & 1) == 1 ? -1 : 1) *
//                            ((n & 1) == 0 ? -1 : 1) *
//                            Math.scalb(1.0, v - 1) *
//                            Math.pow(Math.PI, v) * B2N[n] / BoostGamma.uncheckedFactorial(v);
//                    }
//                } else if ((v & 1) == 1) {
//                    // Positive odd integer with s != 1.
//                    // For odd integers zetaImp53 is exact except for 1 ULP at s=53. The exact
//                    // values are included here as the documentation notes:
//                    // "as these are of great benefit to some infinite series calculations".
//                    // The function remains monototic for zeta(s) at s=53.
//                    final int i = (v - 3) / 2;
//                    return i < ZETA_ODD_INTEGER.length ? ZETA_ODD_INTEGER[i] : 1;
                }
            }
        }

        double result;
        if (Math.abs(s) < BoostGamma.ROOT_EPSILON) {
            result = -0.5 - BoostGamma.LOG_ROOT_TWO_PI * s;
        } else if (s < 0) {
            // Negative odd integer (all negative even integers handled above).
            // Swap: s is now positive; sc = 1 - s
            double tmp = s;
            s = sc;
            sc = tmp;
            if (s > BoostGamma.MAX_FACTORIAL) {
                // This has been simplified from the Boost implementation which will
                // catch overflow conditions when compiled with an appropriate evaluation
                // policy and return signed infinity, or raise an error. Java floating-point
                // arithmetic does not create overflow exceptions and will return infinity.
                double mult = BoostGamma.sinp(0.5 * sc) * 2 * zetaImp53(s, sc);
                result = LogGamma.value(s);
                result -= s * Math.log(2 * Math.PI);
                // Possible overflow if result > 709
                result = Math.exp(result);
                // Possible overflow.
                // Needs result to be just on the verge of overflow when /s/ is
                // very close to a half integer.
                result *= mult;
            } else {
                result = BoostGamma.sinp(0.5 * sc) *
                    2 * Math.pow(2 * Math.PI, -s) *
                    Gamma.value(s) *
                    zetaImp53(s, sc);
            }
        } else {
            result = zetaImp53(s, sc);
        }
        return result;
    }

