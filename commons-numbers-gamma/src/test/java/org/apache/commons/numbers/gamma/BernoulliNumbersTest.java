    /**
     * Negative n or large even n are not supported.
     */
    @ParameterizedTest
    @ValueSource(ints = {-1, -72893497, 376492})
    void testUnsupportedThrows(int n) {
        Assertions.assertFalse(BernoulliNumbers.isSupported(n));
        Assertions.assertThrows(IllegalArgumentException.class, () -> BernoulliNumbers.value(n));
    }

    /** B_1 == -0.5. B_{2n+1} == 0.0 for n above zero, i.e. all odd numbers above 1. */
    @ParameterizedTest
    @ValueSource(ints = {1, 3, 33, 72893497})
    void testOdd(int n) {
        final double expected = n == 1 ? -0.5 : 0.0;
        Assertions.assertTrue(BernoulliNumbers.isSupported(n));
        Assertions.assertEquals(expected, BernoulliNumbers.value(n).doubleValue());
    }

